/**
 * 欧文の正規化。前後の空白を削り、連続する空白(全角空白・タブを含む)を
 * 半角空白1つにまとめ、半角英字を大文字にする。
 * 対応外の文字は消さずに残す(作成画面で主催者が気づけるように)。
 *
 * @param {string} input 入力された文字列
 * @returns {string} 正規化後の文字列
 */
function normalizeEn(input) {
  // 全角英字などを大文字化で別の文字に変えないよう、半角英字だけを対象にする
  return input
    .trim()
    .replace(/\s+/g, ' ')
    .replace(/[a-z]/g, (ch) => ch.toUpperCase());
}

/** @type {MorseTable} */
export const EN_TABLE = Object.freeze({
  lang: 'en',
  codes: EN_CODES,
  normalize: normalizeEn,
});
